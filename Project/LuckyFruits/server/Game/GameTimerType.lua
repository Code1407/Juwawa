-- ============================================================
-- GameTimerType 模块：游戏计时器类型定义
-- 基于 TimerType 基础类型扩展，定义游戏业务相关的计时器ID。
-- 所有游戏计时器ID从 TT_TimerEnd+1 开始递增，避免与基础计时器冲突。
-- 被各业务模块用于注册定时任务（如心跳、轮询、延迟回调）。
-- ============================================================

require "TimerType"

GameTimerType = {
    GTT_TimerStart = TimerType.TT_TimerEnd + 1, -- 游戏计时器起始ID，所有游戏计时器ID从此值开始递增
}